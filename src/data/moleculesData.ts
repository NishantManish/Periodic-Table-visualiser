/**
 * Normalize any subscripted or plain formula (e.g. "C₂H₆O" or "C2H6O") to plain ASCII ("C2H6O").
 */
export function normalizeFormulaAscii(formula: string): string {
  const map: Record<string, string> = {
    '₀': '0',
    '₁': '1',
    '₂': '2',
    '₃': '3',
    '₄': '4',
    '₅': '5',
    '₆': '6',
    '₇': '7',
    '₈': '8',
    '₉': '9',
  };
  return formula
    .replace(/[₀-₉]/g, (ch) => map[ch] || ch)
    .replace(/\s+/g, '')
    .trim();
}

/**
 * Find all structural formations (isomers/allotropes) sharing the same isomerGroup or ASCII formula.
 */
export function getIsomersForMolecule(mol: MoleculeDossier, library: MoleculeDossier[] = MOLECULES_LIBRARY): MoleculeDossier[] {
  const normFormula = normalizeFormulaAscii(mol.formula);
  return library.filter(
    (m) =>
      m.isomerGroup === mol.isomerGroup ||
      normalizeFormulaAscii(m.formula) === normFormula
  );
}
